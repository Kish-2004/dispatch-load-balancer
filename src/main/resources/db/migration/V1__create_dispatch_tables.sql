CREATE TABLE delivery_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(50) NOT NULL UNIQUE,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    address VARCHAR(255) NOT NULL,
    package_weight NUMERIC(12, 3) NOT NULL,
    priority VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_order_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_order_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_order_weight CHECK (package_weight > 0),
    CONSTRAINT chk_order_priority CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW'))
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id VARCHAR(50) NOT NULL UNIQUE,
    capacity NUMERIC(12, 3) NOT NULL,
    current_latitude DOUBLE PRECISION NOT NULL,
    current_longitude DOUBLE PRECISION NOT NULL,
    current_address VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_vehicle_capacity CHECK (capacity > 0),
    CONSTRAINT chk_vehicle_latitude CHECK (current_latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_vehicle_longitude CHECK (current_longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_delivery_orders_priority ON delivery_orders (priority);
